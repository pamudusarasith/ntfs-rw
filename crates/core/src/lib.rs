//! An NTFS filesystem implementation in pure Rust.
//!
//! `ntfs-rw` aims to read and write NTFS volumes without depending on
//! any C library, with a `no_std` core so it can run beyond desktop
//! operating systems.
//!
//! **Status:** early development. Nothing is usable yet, and the API
//! will change without notice. Follow progress at
//! <https://github.com/pamudusarasith/ntfs-rw>.
